import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const here = new URL("./", import.meta.url);
const { outputFiles, metafile } = await build({
  absWorkingDir: fileURLToPath(here),
  entryPoints: ["surface.js"],
  bundle: true,
  format: "iife",
  globalName: "A2ContextA2UI",
  target: "es2022",
  minify: true,
  metafile: true,
  write: false,
});
const inputs = Object.values(metafile.outputs)[0].inputs;
const packages = [...new Set(Object.entries(inputs).filter(([, input]) => input.bytesInOutput)
  .map(([path]) => path.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean))].sort();
const licenses = ["Third-party licenses for the bundled A2UI renderer."];
for (const name of packages) {
  const folder = new URL(`node_modules/${name}/`, here);
  const metadata = JSON.parse(await readFile(new URL("package.json", folder), "utf8"));
  const license = await readFile(new URL("LICENSE", folder), "utf8");
  licenses.push(`${name} ${metadata.version}\n\n${license.trim()}`);
}
const outputs = [
  ["../sidecar-a2ui.js", "// Generated by npm run build in ui/a2ui.\n" + outputFiles[0].text],
  ["../../LICENSES/A2UI-JavaScript.txt", licenses.join("\n\n---\n\n") + "\n"],
];
for (const [path, contents] of outputs) {
  const file = new URL(path, here);
  if (process.argv.includes("--check")) {
    if (await readFile(file, "utf8") !== contents) throw new Error(`${path} is stale. Run npm run build in ui/a2ui.`);
  } else {
    await writeFile(file, contents);
  }
}
