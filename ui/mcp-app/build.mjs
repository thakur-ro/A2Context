import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const here = new URL("./", import.meta.url);
const html = await readFile(new URL("view.html", here), "utf8");
const { outputFiles, metafile } = await build({
  absWorkingDir: fileURLToPath(here),
  entryPoints: ["view.js"],
  bundle: true,
  minify: true,
  format: "esm",
  legalComments: "inline",
  metafile: true,
  write: false,
});
const js = outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const output = new URL("../mcp-app.html", here);
const bundled = "<!-- Generated by npm run build in ui/mcp-app. -->\n"
  + html.replace("<!-- BUNDLE -->", () => "<script type=\"module\">\n" + js + "</script>");
const inputs = Object.values(metafile.outputs)[0].inputs;
const packages = [...new Set(Object.entries(inputs).filter(([, info]) => info.bytesInOutput)
  .map(([path]) => path.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean))].sort();
const licenses = ["Third-party licenses for the bundled MCP App browser code."];
for (const name of packages) {
  const folder = new URL("node_modules/" + name + "/", here);
  const metadata = JSON.parse(await readFile(new URL("package.json", folder), "utf8"));
  const license = await readFile(new URL("LICENSE", folder), "utf8");
  licenses.push(name + " " + metadata.version + "\n\n" + license.trim());
}
const notices = new URL("../../LICENSES/MCP-App-JavaScript.txt", here);
for (const [path, contents] of [[output, bundled], [notices, licenses.join("\n\n---\n\n") + "\n"]]) {
  if (process.argv.includes("--check")) {
    if (await readFile(path, "utf8") !== contents) throw new Error(path.pathname + " is stale. Run npm run build in ui/mcp-app.");
  } else {
    await writeFile(path, contents);
  }
}
